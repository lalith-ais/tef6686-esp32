// ==========================================================================
// Raw I2C write (no command framing — used for patch protocol and boot)
// ==========================================================================
static esp_err_t raw_write(const uint8_t *data, size_t len)
{
    return i2c_master_transmit(tef_handle, data, len, 100);
}

// ==========================================================================
// TEF command write: [module][cmd][0x01][p1_hi][p1_lo][p2_hi][p2_lo]...
// This is the correct format as per Tuner_Drv_Lithio.cpp devTEF_Set_Cmd()
// ==========================================================================
static esp_err_t tef_cmd(uint8_t module, uint8_t cmd,
                          int16_t p1, int16_t p2, int16_t p3, int8_t nparams)
{
    uint8_t buf[9];
    buf[0] = module;
    buf[1] = cmd;
    buf[2] = 0x01;  // ← this byte was missing in v1/v2!
    int len = 3;
    if (nparams >= 1) { buf[len++] = p1 >> 8; buf[len++] = p1 & 0xFF; }
    if (nparams >= 2) { buf[len++] = p2 >> 8; buf[len++] = p2 & 0xFF; }
    if (nparams >= 3) { buf[len++] = p3 >> 8; buf[len++] = p3 & 0xFF; }
    return i2c_master_transmit(tef_handle, buf, len, 100);
}

// ==========================================================================
// TEF read: STOP-then-START (two separate transactions).
// The Arduino Wire library uses endTransmission(true) = STOP, then
// requestFrom() = new START. The TEF6686 requires this — repeated-start
// causes it to echo the command bytes back instead of returning data.
// ==========================================================================
static esp_err_t tef_read(uint8_t module, uint8_t cmd, uint8_t *out, size_t len)
{
    uint8_t reg[3] = { module, cmd, 0x01 };
    esp_err_t ret = i2c_master_transmit(tef_handle, reg, 3, 100);
    if (ret != ESP_OK) return ret;
    vTaskDelay(pdMS_TO_TICKS(3));
    return i2c_master_receive(tef_handle, out, len, 100);
}

// ==========================================================================
// Patch upload
// ==========================================================================
static esp_err_t patch_load(const uint8_t *data, size_t size)
{
    uint8_t buf[25];
    buf[0] = 0x1B;  // patch command prefix
    while (size) {
        size_t chunk = (size > 24) ? 24 : size;
        memcpy(&buf[1], data, chunk);
        esp_err_t ret = raw_write(buf, chunk + 1);
        if (ret != ESP_OK) return ret;
        data += chunk;
        size -= chunk;
        vTaskDelay(pdMS_TO_TICKS(2));
    }
    return ESP_OK;
}

static esp_err_t tef_upload_patch(void)
{
    esp_err_t ret;
    uint8_t cmd3[3];

    // 1. Unlock patch memory
    uint8_t unlock[] = { 0x1E, 0x5A, 0x01, 0x5A, 0x5A };
    ret = raw_write(unlock, sizeof(unlock)); if (ret != ESP_OK) return ret;
    vTaskDelay(pdMS_TO_TICKS(100));

    // 2. Select patch bank
    cmd3[0]=0x1C; cmd3[1]=0x00; cmd3[2]=0x00;
    ret = raw_write(cmd3, 3); if (ret != ESP_OK) return ret;
    vTaskDelay(pdMS_TO_TICKS(100));

    cmd3[2] = 0x74;  // patch mode
    ret = raw_write(cmd3, 3); if (ret != ESP_OK) return ret;

    // 3. Upload patch bytes
    ESP_LOGI(TAG, "Uploading patch (%d bytes)...", (int)sizeof(patch_v102));
    ret = patch_load(patch_v102, sizeof(patch_v102));
    if (ret != ESP_OK) return ret;

    // 4. Close patch bank
    cmd3[2] = 0x00;
    ret = raw_write(cmd3, 3); if (ret != ESP_OK) return ret;
    vTaskDelay(pdMS_TO_TICKS(100));

    // 5. Select LUT bank
    cmd3[2] = 0x75;
    ret = raw_write(cmd3, 3); if (ret != ESP_OK) return ret;

    // 6. Upload LUT bytes
    ESP_LOGI(TAG, "Uploading LUT (%d bytes)...", (int)sizeof(lut_v102));
    ret = patch_load(lut_v102, sizeof(lut_v102));
    if (ret != ESP_OK) return ret;

    // 7. Close LUT bank
    cmd3[2] = 0x00;
    ret = raw_write(cmd3, 3);
    vTaskDelay(pdMS_TO_TICKS(100));

    ESP_LOGI(TAG, "Patch upload complete");
    return ret;
}

// ==========================================================================
// Crystal init for 12.000 MHz (tuner_init_tab12000 from source)
// ==========================================================================
static esp_err_t tef_crystal_init_12000(void)
{
    esp_err_t ret;

    // Entry 1: [3 bytes] 0x14 0x00 0x01  -- soft reset
    uint8_t reset[] = { 0x14, 0x00, 0x01 };
    ret = raw_write(reset, sizeof(reset));
    if (ret != ESP_OK) return ret;

    vTaskDelay(pdMS_TO_TICKS(50));

    // Entry 2: [9 bytes] 0x40 0x04 0x01 0x00 0xB7 0x1B 0x00 0x00 0x00
    // APPL_Set_ReferenceClock: 0x00B71B00 = 12,000,000 Hz (type 0x0000 = crystal)
    uint8_t clk[] = { 0x40, 0x04, 0x01, 0x00, 0xB7, 0x1B, 0x00, 0x00, 0x00 };
    ret = raw_write(clk, sizeof(clk));
    if (ret != ESP_OK) return ret;

    // Entry 3: [5 bytes] 0x40 0x05 0x01 0x00 0x01
    // APPL_Set_GPIO
    uint8_t gpio[] = { 0x40, 0x05, 0x01, 0x00, 0x01 };
    ret = raw_write(gpio, sizeof(gpio));
    if (ret != ESP_OK) return ret;

    vTaskDelay(pdMS_TO_TICKS(100));
    return ESP_OK;
}

